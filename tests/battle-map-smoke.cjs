const { _electron, expect } = require('playwright/test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { version } = require('../package.json');

(async () => {
  const env = { ...process.env, DM_SCREEN_TEST: '1', DM_SCREEN_DATA: path.resolve('test-results', 'battle-map-' + Date.now()) };
  delete env.ELECTRON_RUN_AS_NODE;
  const executablePath = process.env.DM_SCREEN_EXECUTABLE;
  const app = await _electron.launch({ executablePath: executablePath || require('electron'), args: executablePath ? [] : [path.resolve('.')], env });
  try {
    const master = await app.firstWindow();
    await expect(master.locator('#version')).toHaveText(`v${version}`);
    const dispatch = (type, payload) => master.evaluate(async ({ type, payload }) => {
      const response = await dm.dispatch(type, payload);
      if (!response.ok) throw new Error(response.error);
      return (await dm.init()).state;
    }, { type, payload });
    const inspect = page => page.evaluate(async () => (await dm.init()).state);
    await master.keyboard.press('Escape');
    await expect(master.locator('#quit-adventuricon')).toBeVisible();
    await master.keyboard.press('Escape');
    await master.click('#add-combatant');
    await master.fill('#combatant-form [name="name"]', 'Каменный страж');
    await master.selectOption('#combatant-form [name="tokenSize"]', '3');
    await master.click('#token-frame-picker summary');
    await expect(master.locator('#token-frame-options button')).toHaveCount(40);
    await expect(master.locator('[data-frame="ruby"]')).toBeVisible();
    await master.click('[data-frame="phoenix"]');
    await master.click('#editor-submit');
    const guard = (await inspect(master)).combatants[0];
    assert.equal(guard.tokenFrame, 'phoenix');
    assert.equal(guard.tokenSize, 3);
    await dispatch('token:add', { id: guard.id, col: 3, row: 2 });
    await master.click('#fit-map');
    const token = master.locator('#map-tokens [data-token]');
    await expect(token).toHaveAttribute('data-size', '3');
    await expect(token.locator('.pixel-token-frame')).toHaveAttribute('data-shape', 'wings');
    const size = await token.evaluate(node => ({
      token: node.offsetWidth,
      grid: parseFloat(getComputedStyle(node).getPropertyValue('--grid-size')),
    }));
    assert.ok(Math.abs(size.token - size.grid * 3) <= 1, JSON.stringify(size));
    const opened = app.waitForEvent('window');
    await master.click('[data-detach="map"]');
    const player = await opened;
    await expect(player.locator('#map-tokens [data-token]')).toHaveCount(1);
    await expect(player.locator('#map-tokens .pixel-token-frame')).toHaveAttribute('data-shape', 'wings');
    await token.click({ button: 'right' });
    await master.click('#token-toggle-visibility');
    await expect(token.locator('.token-secret')).toBeVisible();
    await expect(player.locator('#map-tokens [data-token]')).toHaveCount(0);
    const hidden = await inspect(player);
    assert.equal(hidden.mapCombatants.some(actor => actor.id === guard.id), false);
    await master.click('#reveal-hidden-enemies');
    await expect(player.locator('#map-tokens [data-token]')).toHaveCount(1);

    await token.click({ button: 'right' });
    await expect(master.locator('#token-vision-label')).toHaveText('30 фут.');
    await master.click('#token-raise');
    await master.fill('#token-map-settings [name="elevation"]', '-10');
    await master.locator('#token-map-settings [name="visionFeet"]').evaluate(input => {
      input.value = '65';
      input.dispatchEvent(new Event('input'));
    });
    await master.click('#token-map-settings [type="submit"]');
    await expect(token.locator('.token-elevation')).toHaveText('−10 фут.');
    await expect(player.locator('.token-elevation')).toHaveText('−10 фут.');
    assert.equal((await inspect(master)).tokens[0].visionFeet, 65);

    const viewport = master.locator('#map-viewport');
    const measureOverlay = master.locator('#map-measure-overlay');
    await expect(measureOverlay).toBeHidden();
    const bounds = await viewport.boundingBox();
    const x = bounds.x + bounds.width / 2, y = bounds.y + bounds.height / 2;
    await master.click('[data-map-tool="circle"]');
    await master.mouse.click(x, y);
    await expect(measureOverlay).toBeVisible();
    await expect(master.locator('#map-measure-label')).toHaveText('15 фут. · радиус');
    await master.mouse.wheel(0, -120);
    await expect(master.locator('#map-measure-label')).toHaveText('20 фут. · радиус');
    await master.keyboard.press('Escape');
    await expect(measureOverlay).toBeHidden();
    for (const [tool, suffix] of [['line', ''], ['square', ' · сторона'], ['cone', '']]) {
      await master.click(`[data-map-tool="${tool}"]`);
      await master.mouse.click(x, y);
      await expect(master.locator('#map-measure-overlay')).toHaveAttribute('data-measure', tool);
      await expect(master.locator('#map-measure-label')).toHaveText('15 фут.' + suffix);
      await master.keyboard.press('Escape');
    }
    await master.click('[data-map-tool="circle"]');
    await master.mouse.click(x, y);
    await expect(master.locator('#map-tool-apply')).toHaveText('Оставить на карте');
    await master.click('#map-tool-apply');
    const marker = master.locator('[data-template-handle]');
    const masterTemplate = master.locator('#map-templates [data-map-template]');
    const playerTemplate = player.locator('#map-templates [data-map-template]');
    await expect(marker).toHaveCount(1);
    await expect(measureOverlay).toBeHidden();
    await expect(playerTemplate).toHaveCount(1);
    await marker.click();
    await expect(master.locator('#map-templates .selected')).toHaveCount(1);
    await marker.click({ button: 'right' });
    await master.click('#map-template-remove');
    await expect(masterTemplate).toHaveCount(0);
    await expect(playerTemplate).toHaveCount(0);
    await expect(measureOverlay).toBeHidden();
    assert.equal((await inspect(master)).templates.length, 0);
    const original = (await inspect(master)).map;
    const gridDialog = master.locator('#grid-dialog');
    const gridHint = master.locator('#map-tool-hint');
    await expect(master.locator('#map-quick-tools')).not.toContainText('Сетка мышью');
    await master.click('#map-settings');
    await gridDialog.locator('[name="grid"]').fill('104');
    await gridDialog.getByRole('button', { name: 'Сетка мышью' }).click();
    await expect(gridDialog).toBeHidden();
    await expect(gridHint).toContainText('104 px');
    await master.keyboard.press('Escape');
    await expect(gridHint).toBeHidden();
    assert.deepEqual((await inspect(master)).map, original);

    await master.click('#map-settings');
    await gridDialog.locator('[name="grid"]').fill('511');
    await gridDialog.locator('[name="offsetX"]').fill('35');
    await gridDialog.locator('[name="diagonals"]').selectOption('alternating');
    await gridDialog.getByRole('button', { name: 'Сетка мышью' }).click();
    await expect(gridHint).toContainText('511 px · X 35');
    const gridBounds = await viewport.boundingBox();
    const gx = gridBounds.x + gridBounds.width / 2, gy = gridBounds.y + gridBounds.height / 2;
    await master.mouse.move(gx, gy);
    await master.mouse.down();
    await master.mouse.move(gx + 26, gy + 12);
    await master.mouse.up();
    await master.mouse.wheel(0, -120);
    await expect(gridHint).toContainText('512 px');
    const beforeNudge = await gridHint.textContent();
    await viewport.dispatchEvent('wheel', { deltaY: -120, altKey: true });
    await expect(gridHint).not.toHaveText(beforeNudge);
    await master.click('#map-tool-apply');
    const updated = (await inspect(master)).map;
    assert.equal(updated.grid, 512);
    assert.notEqual(updated.offsetX, 35);
    assert.equal(updated.diagonals, 'alternating');
    const saved = (await inspect(master)).tokens[0];
    assert.deepEqual([saved.col, saved.row], [3, 2]);
    await master.click('#map-settings');
    const gridField = gridDialog.locator('[name="grid"]');
    await expect(gridField).toHaveValue('512');
    await gridField.fill('513');
    assert.equal(await gridField.evaluate(input => input.validity.rangeOverflow), true);
    await gridField.fill('512');
    await gridDialog.locator('[type="submit"]').click();
    await expect(gridDialog).toBeHidden();

    await master.click('#show-notes');
    await master.click('[data-story-tool="text"]');
    await master.locator('#story-viewport').click({ position: { x: 70, y: 100 } });
    await master.fill('#story-body', 'Здесь ждёт проводник\nПароль: маяк');
    await master.click('#story-form [type="submit"]');
    await expect(master.locator('.story-free-text')).toContainText('Здесь ждёт проводник');
    assert.equal((await inspect(master)).story.notes[0].kind, 'text');
    await master.keyboard.press('Escape');
    const closed = app.waitForEvent('close');
    await master.click('#quit-adventuricon');
    await closed;
    console.log('PASS: frames, private tokens, elevation, vision settings, saved templates, grid adjustment, free text and quit.');
  } finally { await app.close().catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
