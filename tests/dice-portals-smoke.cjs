const { _electron, expect } = require('playwright/test');
const assert = require('node:assert/strict');
const path = require('node:path');

(async () => {
  const env = { ...process.env, DM_SCREEN_TEST: '1', DM_SCREEN_DATA: path.resolve('test-results', 'portals-' + Date.now()) };
  delete env.ELECTRON_RUN_AS_NODE;
  const executablePath = process.env.DM_SCREEN_EXECUTABLE;
  const app = await _electron.launch({ executablePath: executablePath || require('electron'), args: executablePath ? [] : [path.resolve('.')], env });
  try {
    const page = await app.firstWindow();
    await expect(page.locator('#version')).toHaveText(`v${require('../package.json').version}`);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const action = (type, payload) => page.evaluate(async ({ type, payload }) => {
      const result = await dm.dispatch(type, payload);
      if (!result.ok) throw new Error(result.error);
      return (await dm.init()).state;
    }, { type, payload });
    await page.click('#screen-settings');
    await page.getByRole('button', { name: 'Лунное серебро' }).click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'moon');
    await expect.poll(() => page.locator('#theme-brand-icon').evaluate(image => image.naturalWidth)).toBe(256);
    await page.getByRole('button', { name: 'Старый пергамент' }).click();
    await expect(page.locator('html')).toHaveCSS('color-scheme', 'light');
    await expect(page.locator('#theme-brand-icon')).toHaveAttribute('src', 'assets/themes/parchment.png');
    await expect.poll(() => page.locator('#theme-brand-icon').evaluate(image => image.naturalWidth)).toBe(256);
    await page.keyboard.press('Escape');
    await page.click('#toggle-dice-menu');
    await expect(page.locator('#dice-pool button')).toHaveCount(8);
    await page.click('[data-dice-check=kh]');
    await page.click('[data-dice-mod="1"]');
    await expect(page.locator('#dice-form [name=formula]')).toHaveValue('2d20kh1+1');
    await page.click('#save-dice');
    await page.click('#dice-form [type=submit]');
    await expect(page.locator('#dice-result s')).toHaveCount(1);
    await expect(page.locator('#dice-history li')).toHaveCount(1);
    await page.keyboard.press('Escape');
    await expect(page.locator('#dice-menu')).toBeHidden();
    await page.keyboard.press('Control+Alt+d');
    await expect(page.locator('#dice-menu')).toBeVisible();
    await page.click('#toggle-dice-menu');
    await expect(page.locator('#dice-menu')).toBeHidden();

    const initial = await action('combatant:add', { name: 'Мира', role: 'player' });
    const source = initial.activeMapId;
    const actor = initial.combatants[0].id;
    await action('token:add', { id: actor, col: 3, row: 4 });
    const target = (await action('map:create', { title: 'Подвал', fog: true })).activeMapId;
    await action('map:select', { id: source });
    await page.click('#edit-terrain');
    await page.click('#create-map-portal');
    await page.fill('#map-portal-editor [name=name]', 'Лестница');
    await page.click('#portal-pick-exit');
    await expect(page.locator('#portal-exit-map')).toBeVisible();
    await page.locator('#portal-exit-map').click({ position: { x: 46, y: 40 } });
    assert.equal((await page.locator('#map-select').inputValue()), source);
    const col = await page.locator('#map-portal-editor [name=col]').inputValue();
    const row = await page.locator('#map-portal-editor [name=row]').inputValue();
    await page.click('#map-portal-editor [type=submit]');
    await expect(page.locator('#placement-hint')).toBeVisible();
    const point = await page.evaluate(() => {
      const frame = document.querySelector('#map-frame').getBoundingClientRect();
      const point = MapGeometry.transform(boardProjection.matrix, 3.5 * state.map.grid * boardLayout.zoom, 2.5 * state.map.grid * boardLayout.zoom);
      return { x: frame.x + point.x, y: frame.y + point.y };
    });
    await page.mouse.click(point.x, point.y);
    await expect(page.getByRole('button', { name: 'Лестница', exact: true })).toBeVisible();
    const opened = app.waitForEvent('window');
    await page.evaluate(() => dm.detach('map'));
    const player = await opened;
    assert.equal(await player.locator('[data-portal-id]').count(), 0);
    assert.equal(await player.evaluate(async () => (await dm.init()).state.terrain.some(item => item.kind === 'portal')), false);
    await page.getByRole('button', { name: 'Лестница', exact: true }).click();
    await page.click('#portal-select-party');
    await page.click('#map-portal-travel [type=submit]');
    await expect(page.locator('#map-select')).toHaveValue(target);
    const tokens = await page.evaluate(async () => (await dm.init()).state.tokens);
    assert.deepEqual(tokens, [{ combatantId: actor, col: Number(col), row: Number(row) }]);
    await expect.poll(() => player.evaluate(async () => (await dm.init()).state.activeMapId)).toBe(target);
    await page.click('#undo-map');
    await expect(page.locator('#map-select')).toHaveValue(source);
    await expect.poll(() => player.evaluate(async () => (await dm.init()).state.activeMapId)).toBe(source);
    assert.deepEqual(await page.evaluate(async () => (await dm.init()).state.tokens), [{ combatantId: actor, col: 3, row: 4 }]);

    if (await page.locator('#close-terrain').isVisible()) await page.click('#close-terrain');
    await page.click('#open-session-scenes');
    await page.click('#new-session-scene');
    await page.fill('#session-scene-form [name=title]', 'Дождь в подвале');
    await page.check('#session-scene-form [name=soundEnabled]');
    await page.check('#scene-ambient-loops [value=rain]');
    await page.locator('[name=musicVolume]').fill('32');
    await page.locator('[name=ambientVolume]').fill('44');
    await page.click('#session-scene-form [type=submit]');
    await page.getByRole('button', { name: 'Дождь в подвале', exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await dm.init()).activePads)).toEqual(['rain']);
    assert.equal(await page.evaluate(async () => (await dm.init()).state.music.volume), .32);
    assert.equal(await page.evaluate(async () => (await dm.init()).state.scenes[0].sound.ambientVolume), .44);
    const combatOpened = app.waitForEvent('window');
    await page.evaluate(() => dm.detach('combat'));
    const combat = await combatOpened;
    await combat.click('#open-tracker-dice');
    await expect(combat.locator('#dice-menu')).toBeVisible();
    assert.deepEqual(errors, []);
    console.log('PASS: themes, global and tracker dice, map transitions and scene ambience');
  } finally { await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
