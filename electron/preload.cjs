const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('dm', {
  init: () => ipcRenderer.invoke('init'),
  setTheme: id => ipcRenderer.invoke('set-theme', id),
  setShortcuts: bindings => ipcRenderer.invoke('set-shortcuts', bindings),
  campaign: payload => ipcRenderer.invoke('campaign', payload),
  campaignSearch: payload => ipcRenderer.invoke('campaign-search', payload),
  workspaceCommand: payload => ipcRenderer.invoke('workspace-command', payload),
  masterShortcut: command => ipcRenderer.invoke('master-shortcut', command),
  undoMap: context => ipcRenderer.invoke('map-undo', context),
  dispatch: (type, payload) => ipcRenderer.invoke('dispatch', { type, payload }),
  importFile: kind => ipcRenderer.invoke('import-file', { kind }),
  importDrop: (file, kind) => ipcRenderer.invoke('import-drop', { path: webUtils.getPathForFile(file), kind }),
  importLss: (file, expectedBattleId) => ipcRenderer.invoke('import-lss', { file: file ? webUtils.getPathForFile(file) : null, expectedBattleId }),
  readDndCard: (url, kind) => ipcRenderer.invoke('read-dnd-card', { url, kind }),
  readDndIcon: url => ipcRenderer.invoke('read-dnd-icon', url),
  pasteImage: () => ipcRenderer.invoke('paste-image'),
  detach: id => ipcRenderer.invoke('detach', id),
  showToken: id => ipcRenderer.invoke('show-token', id),
  placeToken: placement => ipcRenderer.invoke('place-token', placement),
  showPlayers: (source, id) => ipcRenderer.invoke('show-players', { source, id }),
  mirrorMap: preview => ipcRenderer.send('mirror-map', preview),
  rotatePlayerMap: (delta, context) => ipcRenderer.invoke('rotate-player-map', { ...context, delta }),
  dock: () => ipcRenderer.invoke('dock'),
  fullscreen: () => ipcRenderer.invoke('fullscreen'),
  resizeWindow: bounds => ipcRenderer.send('resize-window', bounds),
  remoteBounds: (id, bounds) => ipcRenderer.send('remote-bounds', { id, bounds }),
  remoteAction: (id, action) => ipcRenderer.invoke('remote-action', { id, action }),
  referenceAction: (action, value) => ipcRenderer.invoke('reference-action', { action, value }),
  downloadMusic: (url, folder) => ipcRenderer.invoke('download-music', { url, folder }),
  cancelMusic: () => ipcRenderer.invoke('cancel-music'),
  update: action => ipcRenderer.invoke('update', action),
  onState: fn => { const listener = (_, value) => fn(value); ipcRenderer.on('state', listener); return () => ipcRenderer.removeListener('state', listener); },
  onStatus: fn => { const listener = (_, value) => fn(value); ipcRenderer.on('status', listener); return () => ipcRenderer.removeListener('status', listener); }
});
